#!/usr/bin/env python3
"""Compute decompilation progress and update README.md.

A function counts as done when a source file under src/ carries a tag

    // @func 0x00463658 main

directly above its reimplementation. Unfinished functions keep a
`// TODO(0x........ name)` comment and do not count.

Usage: python3 tools/progress.py [--check]
"""
import os, re, sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
TAG = re.compile(r'//\s*@func\s+0x([0-9A-Fa-f]{8})\b')
BEGIN, END = '<!-- progress:begin -->', '<!-- progress:end -->'


def load_functions():
    funcs = {}
    with open(os.path.join(ROOT, 'docs', 'functions.tsv')) as f:
        for line in f:
            if line.startswith('#') or not line.strip():
                continue
            addr, size, region = line.split('\t')
            funcs[int(addr, 16)] = (int(size), region.strip())
    return funcs


def scan_tags():
    done = {}
    for base, _, files in os.walk(os.path.join(ROOT, 'src')):
        for name in files:
            if not name.endswith(('.cpp', '.h', '.hpp', '.inl')):
                continue
            path = os.path.join(base, name)
            with open(path, encoding='utf-8', errors='replace') as f:
                for m in TAG.finditer(f.read()):
                    done[int(m.group(1), 16)] = os.path.relpath(path, ROOT)
    return done


def bar(pct, width=30):
    filled = int(round(pct / 100 * width))
    return '`' + '█' * filled + '░' * (width - filled) + '`'


def main():
    funcs = load_functions()
    done = scan_tags()
    unknown = sorted(a for a in done if a not in funcs)
    regions = {}
    for addr, (size, region) in funcs.items():
        r = regions.setdefault(region, [0, 0, 0, 0])
        r[0] += 1
        r[1] += size
        if addr in done:
            r[2] += 1
            r[3] += size
    total = sum(r[0] for r in regions.values())
    total_b = sum(r[1] for r in regions.values())
    ndone = sum(r[2] for r in regions.values())
    ndone_b = sum(r[3] for r in regions.values())
    pct = 100.0 * ndone / total
    pct_b = 100.0 * ndone_b / total_b

    labels = {'game': 'Game + Ape engine', 'sdk': 'C runtime / SPU job support', 'sonyaudio': 'Sony audio (989snd, MultiStream)',
              'navpower': 'NavPower navigation (middleware)', 'bink': 'Bink video (middleware)', 'havok': 'Havok 2011.3 (middleware)'}
    lines = [BEGIN, '',
             '## Progress: **%.2f%%**' % pct, '',
             bar(pct) + '  %d / %d functions (%.2f%% of code bytes)' % (ndone, total, pct_b), '',
             '| Region | Functions done | Total | % (functions) | % (bytes) |',
             '|---|---:|---:|---:|---:|']
    for key in ('game', 'sdk', 'sonyaudio', 'navpower', 'bink', 'havok'):
        if key in regions:
            n, b, d, db = regions[key]
            lines.append('| %s | %d | %d | %.2f%% | %.2f%% |' % (labels[key], d, n, 100.0 * d / n, 100.0 * db / b))
    lines += ['', '_Generated by `tools/progress.py`._', '', END]
    block = '\n'.join(lines)

    readme_path = os.path.join(ROOT, 'README.md')
    readme = open(readme_path, encoding='utf-8').read()
    if BEGIN in readme and END in readme:
        new = readme[:readme.index(BEGIN)] + block + readme[readme.index(END) + len(END):]
    else:
        new = readme.rstrip() + '\n\n' + block + '\n'
    if '--check' in sys.argv:
        print('%d/%d functions (%.2f%%)' % (ndone, total, pct))
        return
    with open(readme_path, 'w', encoding='utf-8') as f:
        f.write(new)
    if unknown:
        print('warning: tags not in docs/functions.tsv:', ' '.join('0x%08X' % a for a in unknown))
    print('%d/%d functions (%.2f%%)' % (ndone, total, pct))


if __name__ == '__main__':
    main()
